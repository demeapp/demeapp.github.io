def past_voice(brief):
    if not brief:
        return brief
    out = brief
    lead = 90  # the lead construction starts within this window
    m = re.search(r"\bwill\s+re-([a-z]+)", out, re.I)
    if m and m.start() < lead and m.group(1).lower() in PAST_VERBS:
        out = out.replace(m.group(0),
                          "re-" + PAST_VERBS[m.group(1).lower()], 1)
    m = re.search(r"\bwill\s+(not\s+|also\s+|formally\s+|privately\s+|"
                  r"fully\s+|again\s+)?([a-z]+)", out, re.I)
    if m and m.start() < lead:
        whole, adv, verb_raw = m.group(0), m.group(1), m.group(2)
        verb = verb_raw.lower()
        if adv and adv.strip() == "not":
            out = out.replace(whole, "did not " + verb_raw, 1)
        elif verb == "be":
            tail = out[m.start() + len(whole):]
            part = re.match(r"\s+([a-z]+)", tail, re.I)
            if part and (re.search(r"(ed|en|ing)$", part.group(1).lower())
                         or part.group(1).lower()
                         in ("held", "given", "made", "set", "put")):
                out = out[:m.start()] + "was" + tail
        elif verb in PAST_VERBS:
            adv_text = (adv.strip() + " ") if adv else ""
            out = out.replace(whole, adv_text + PAST_VERBS[verb], 1)
    m = re.search(r"\b(is|are) asked to", out, re.I)
    if m and m.start() < lead:
        out = out.replace(m.group(0),
                          "was asked to" if m.group(1).lower() == "is"
                          else "were asked to", 1)
    return out


def truncate(s, limit=200):
    s = " ".join(str(s or "").split())
    if len(s) <= limit:
        return s
    cut = s[:limit - 3]
    if " " in cut:
        cut = cut[:cut.rfind(" ")]
    return cut + "…"


def ordinal(n):
    try:
        n = int(n)
    except (TypeError, ValueError):
        return str(n or "")
    if 10 <= n % 100 <= 20:
        suf = "th"
    else:
        suf = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


