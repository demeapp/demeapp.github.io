def esc(s):
    return html.escape(str(s if s is not None else ""), quote=True)


def fmt_date(iso):
    """Mirror common.js fmtDate(): '2026-10-19' -> 'Oct 19, 2026'.
    A value that is not an ISO date is returned as stored."""
    if not iso:
        return ""
    parts = str(iso)[:10].split("-")
    try:
        y, m, d = (int(p) for p in parts)
        return f"{MONTHS[m - 1]} {d}, {y}"
    except (ValueError, IndexError):
        return str(iso)


def clean_title(t):
    """Mirror common.js cleanTitle(): collapse a doubled honorific."""
    return re.sub(r"\b(Councillor|Mayor|Deputy Mayor)\s+\1\b", r"\1",
                  str(t or ""))


