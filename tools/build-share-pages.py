from urllib.parse import quote


def write_blob(path, blob):
    """Write one generated page — only when its bytes would change.

    Idempotence, literally: a page whose existing bytes already equal
    the generated bytes is left untouched, so re-running the build
    over an unchanged tree performs no writes at all and the output
    is byte-identical by construction.

    A write that IS needed retries transient PermissionError with
    backoff: the build host intermittently refuses file writes for
    short windows (Errno 1, observed Oct 28, 2026 under write bursts),
    and a refused open can leave the previous page truncated, so the
    SAME write is retried until it lands in full. Any other error —
    and a window that outlasts the retries — fails loudly, exactly
    like the count assertions."""
    try:
        if path.read_bytes() == blob:
            return
    except OSError:
        pass  # missing or unreadable: fall through and write it
    delay = 0.5
    for attempt in range(40):
        try:
            path.write_bytes(blob)
            return
        except PermissionError:
            if attempt == 39:
                raise
            time.sleep(delay)
            delay = min(delay * 1.5, 5.0)

