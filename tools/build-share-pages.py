def stats(name, sizes):
    sizes = sorted(sizes)
    n = len(sizes)
    median = sizes[n // 2] if n % 2 else (sizes[n // 2 - 1] + sizes[n // 2]) // 2
    p90 = sizes[min(n - 1, int(n * 0.9))]
    print(f"{name}: {n} pages · total {sum(sizes)} bytes · "
          f"min {sizes[0]} · median {median} · p90 {p90} · max {sizes[-1]}")
    return n


def main():
    total = 0
    total += stats("Toronto decisions (d/)", build_toronto())
    total += stats("Ontario divisions (on/)", build_ontario())
    total += stats("Federal divisions (ca/)", build_federal())
    print(f"TOTAL: {total} share pages written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
