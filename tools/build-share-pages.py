#!/usr/bin/env python3
"""Build the shareable static record pages (INC 3, product wave Oct 28, 2026).

Generates one compact static HTML page per record, so a shared link
previews with the record's own title, brief and outcome instead of the
generic site shell:

  Toronto decisions   record-data/index-<year>.json cards joined with
                      record-data/d/<ref>.json      ->  d/<ref>.html
  Ontario divisions   record-data/ontario/divisions.json
                                                    ->  on/division-<i>.html
  Federal divisions   record-data/federal/divisions.json
                                                    ->  ca/division-<i>.html

(i is the entry's positional index in its layer's divisions array —
the same index the layer member files' vote rows use.)

Binding rules carried from the product brief:
  - recorded-vote participation is never called "attendance";
  - chamber counts are never blended; Toronto units are "decisions",
    Ontario/federal units are "divisions";
  - a member's vote is rendered ONLY from stored vote rows — nothing
    is inferred from party, outcome or colleagues;
  - federal pages carry NO tally numbers: the federal divisions file
    stores no tallies, and counting member rows would not be the
    official tally;
  - reading and sharing never require an account.

Wording mirrored from assets/js/decision.js (the interactive decision
page) so the static snapshot and the live record say the same thing:
the no-recorded-vote notice, the tally-only explanation and the
provenance lines are copied verbatim from that file, and the brief is
rendered through a faithful port of common.js's pastVoice() (with its
PAST_VERBS map) and cleanTitle(), exactly as decision.js renders it.

The build is deterministic: no dates or timestamps are written into
any generated file, iteration order is the data files' own order, and
re-running the script reproduces byte-identical output.

Stdlib only. Run from anywhere:  python3 tools/build-share-pages.py
"""
import html
