def vote_cell(v):
    """Mirror decision.js voteCell() (standard wording)."""
    if v == "Yes":
        return '<span class="voteYes">Yes</span>'
    if v == "No":
        return '<span class="voteNo">No</span>'
    if v and str(v).startswith("Absent(Interest"):
        return ('<span class="voteAbs">Declared an interest — stepped back '
                'from this vote</span>')
    return '<span class="voteAbs">Absent</span>'


def motion_block(m):
    head = esc(m.get("type") or "Motion")
    if m.get("result"):
        head += f" — {esc(m['result'])}"
    stage = esc(m.get("stage") or "City Council")
    if m.get("tallyOnly"):
        # decision.js, verbatim: the result stands alone rather than
        # showing a breakdown the source rows cannot support.
        return f"""<div class="card" style="margin-top:1rem">
<h3>{head}</h3>
<p class="small" style="margin:.1rem 0 .5rem">Vote taken at: <strong>{stage}</strong></p>
<p class="small">{TALLY_ONLY_NOTE}</p>
</div>"""
    votes = m.get("votes") or []
    counts = ""
    if m.get("yes") is not None and m.get("no") is not None:
        counts = (f'<p class="small">Yes: <strong>{esc(m["yes"])}</strong>'
                  f' · No: <strong>{esc(m["no"])}</strong></p>')
    table = ""
    if votes:
        rows = "\n".join(
            f'<tr><td><a href="../councillor.html?name={quote(str(name))}">'
            f'{esc(name)}</a></td><td>{vote_cell(v)}</td></tr>'
            for name, v in votes)
        table = (f'<table class="record"><thead><tr><th scope="col">Member</th>'
                 f'<th scope="col">Vote</th></tr></thead><tbody>{rows}</tbody></table>')
    return f"""<div class="card" style="margin-top:1rem">
<h3>{head}</h3>
<p class="small" style="margin:.1rem 0 .5rem">Vote taken at: <strong>{stage}</strong></p>
{counts}{table}</div>"""


def toronto_page(card, detail):
    ref = card["ref"]
    official = clean_title(card.get("title"))
    brief = past_voice(card.get("brief") or "")
    # Headline choice: the plain-language brief when it exists and is
    # short enough to stand as a headline (<=140 chars), else the
    # official title — the same brief decision.js leads the page with.
    use_brief = bool(brief) and len(brief) <= 140
    headline = brief if use_brief else official
    description = truncate(brief or (detail or {}).get("summary")
                           or official)
    parts = []
    parts.append('<p class="kicker">Toronto City Council · Decision</p>')
    parts.append(f"<h1>{esc(headline)}</h1>")
    if use_brief:
        parts.append(
            f'<p class="small">Official title: {esc(official)}</p>')
    parts.append(
        '<div class="outcomeRow">'
        f'<span class="pill">{esc(card.get("statusLabel") or "")}</span>'
        f'<span class="small">{esc(fmt_date(card.get("date")))}'
        ' · Toronto City Council</span></div>')
    if brief and not use_brief:
        parts.append(f'<p class="briefBig">{esc(brief)}</p>')
    if card.get("stake"):
        parts.append(
            f'<p class="stake stake-prominent">{esc(card["stake"])}</p>')

    detail = detail or {}
    motions = detail.get("motions")
    if card.get("hasVote"):
        if motions:
            parts.append('<h2 style="margin-top:2.2rem">How the vote went</h2>'
                         '<hr class="rule">')
            parts.extend(motion_block(m) for m in motions)
        else:
            parts.append('<h2 style="margin-top:2.2rem">How the vote went</h2>'
                         '<hr class="rule"><p class="small">The vote record '
                         'could not be loaded. The official record is linked '
                         'below.</p>')
    else:
        parts.append(f'<div class="notice">{NO_VOTE_NOTICE}</div>')

    text = detail.get("text") or []
    # Most detail files carry text[proposed, decided]; a small early
    # set carries the same pair as top-level summary/decided fields.
    proposed = (text[0] if len(text) > 0 else "") or detail.get("summary") or ""
    decided = (text[1] if len(text) > 1 else "") or detail.get("decided") or ""
    if proposed or decided:
        parts.append('<h2 style="margin-top:2.2rem">The official record</h2>'
                     '<hr class="rule">')
        if proposed:
            parts.append(f'<h3>What the item proposed</h3>'
                         f'<p style="max-width:44rem">{esc(proposed)}</p>')
        if decided:
            parts.append(f'<h3>What was decided</h3>'
                         f'<p style="max-width:44rem">{esc(decided)}</p>')

    if detail.get("sourceUrl"):
        src_name = detail.get("sourceName") or "Toronto TMMIS — agenda item"
        src_id = detail.get("sourceId") or ref
        status = STATUS_LABEL.get(detail.get("verificationStatus") or "")
        line = (f'<p class="small" style="margin-top:2rem">Source: '
                f'<a class="ext" href="{esc(detail["sourceUrl"])}">'
                f'{esc(src_name)} {esc(src_id)}</a>')
        if status:
            line += f' · {esc(status)}'
        line += '</p>'
        parts.append(line)
        if detail.get("sourceUrlBasis") == "pattern":
            parts.append(f'<p class="small">{PROVENANCE_PATTERN_NOTE}</p>')

    parts.append(
        f'<p style="margin-top:2rem"><a href="{SITE}/decision.html?ref='
        f'{quote(str(ref))}">See this decision in the full record →</a></p>')
    return page(headline, description, f"{SITE}/d/{ref}.html",
                "\n".join(parts))


def build_toronto():
    cards = []
    for year in range(2018, 2027):
        with open(DATA / f"index-{year}.json", encoding="utf-8") as f:
            cards.extend(json.load(f))
    assert len(cards) == EXPECTED["toronto"], \
        f"Toronto: expected {EXPECTED['toronto']} cards, got {len(cards)}"
    assert len({c['ref'] for c in cards}) == len(cards), \
        "Toronto: duplicate refs in the index cards"
    out = ROOT / "d"
    out.mkdir(exist_ok=True)
    sizes = []
    for card in cards:
        detail = None
        path = DATA / "d" / f"{card['ref']}.json"
        if path.exists():
            with open(path, encoding="utf-8") as f:
                detail = json.load(f)
        blob = toronto_page(card, detail).encode("utf-8")
        write_blob(out / f"{card['ref']}.html", blob)
        sizes.append(len(blob))
    return sizes


def ontario_page(i, e):
    headline = e.get("title") or e.get("question") or ""
    canonical = f"{SITE}/on/division-{i}.html"
    desc_bits = [headline]
    if e.get("outcome"):
        tally = e["outcome"]
        if e.get("ayes") is not None and e.get("nays") is not None:
            tally += f" {e['ayes']}–{e['nays']}"
        desc_bits.append(tally)
    if e.get("date"):
        desc_bits.append(str(e["date"]))
    desc_bits.append("Ontario Legislature")
    description = truncate(" — ".join(desc_bits))
    parts = ['<p class="kicker">Ontario Legislature · Division</p>',
             f"<h1>{esc(headline)}</h1>"]
    meta = []
    if e.get("parliament") is not None:
        meta.append(f"{ordinal(e['parliament'])} Parliament")
    if e.get("session") is not None:
        meta.append(f"Session {esc(e['session'])}")
    parts.append(
        '<div class="outcomeRow">'
        + (f'<span class="pill">{esc(e["outcome"])}</span>'
           if e.get("outcome") else "")
        + f'<span class="small">{esc(e.get("date") or "")}</span></div>')
    if meta:
        parts.append(f'<p class="small">{" · ".join(meta)}</p>')
    if e.get("outcome"):
        tally = esc(e["outcome"])
        if e.get("ayes") is not None and e.get("nays") is not None:
            tally += (f' — Ayes: <strong>{esc(e["ayes"])}</strong>'
                      f' · Nays: <strong>{esc(e["nays"])}</strong>')
        parts.append(f'<p>{tally}</p>')
    if e.get("parliament") == 42 or str(e.get("parliament")) == "42":
        parts.append(f'<div class="notice">{esc(ON_42_LABEL)}</div>')
    if e.get("billUrl"):
        parts.append(
            f'<p>Read <a class="ext" href="{esc(e["billUrl"])}">the bill '
            'at the Legislative Assembly</a>.</p>')
    parts.append(
        '<p>Name-by-name votes are on each MPP\'s record page — see the '
        '<a href="../representatives.html?level=ontario">Ontario '
        'representatives</a>.</p>')
    parts.append(
        f'<p class="small">Source: '
        f'<a class="ext" href="{OLA_HOUSE_DOCS}">House documents</a>'
        ' at the Legislative Assembly of Ontario.</p>')
    return page(headline, description, canonical, "\n".join(parts))


def build_ontario():
    with open(DATA / "ontario" / "divisions.json", encoding="utf-8") as f:
        entries = json.load(f)
    assert len(entries) == EXPECTED["ontario"], \
        f"Ontario: expected {EXPECTED['ontario']} divisions, got {len(entries)}"
    out = ROOT / "on"
    out.mkdir(exist_ok=True)
    sizes = []
    for i, e in enumerate(entries):
        blob = ontario_page(i, e).encode("utf-8")
        write_blob(out / f"division-{i}.html", blob)
        sizes.append(len(blob))
    return sizes


def federal_page(i, e):
    headline = e.get("subject") or ""
    canonical = f"{SITE}/ca/division-{i}.html"
    desc_bits = [headline]
    if e.get("result"):
        desc_bits.append(str(e["result"]))
    if e.get("date"):
        desc_bits.append(fmt_date(e["date"]))
    desc_bits.append("House of Commons")
    description = truncate(" — ".join(desc_bits))
    parts = ['<p class="kicker">House of Commons · Division</p>',
             f"<h1>{esc(headline)}</h1>"]
    meta = []
    if e.get("session"):
        meta.append(f"Session {esc(e['session'])}")
    if e.get("number") is not None:
        meta.append(f"Division {esc(e['number'])}")
    if e.get("bill"):
        meta.append(f"Bill {esc(e['bill'])}")
    parts.append(
        '<div class="outcomeRow">'
        + (f'<span class="pill">{esc(e["result"])}</span>'
           if e.get("result") else "")
        + f'<span class="small">{esc(fmt_date(e.get("date")))}</span></div>')
    if meta:
        parts.append(f'<p class="small">{" · ".join(meta)}</p>')
    if e.get("url"):
        parts.append(
            f'<p>See <a class="ext" href="{esc(e["url"])}">the official '
            'division record at the House of Commons</a>.</p>')
    parts.append(
        '<p>Name-by-name votes are on each MP\'s record page — see the '
        '<a href="../representatives.html?level=canada">federal '
        'representatives</a>.</p>')
    return page(headline, description, canonical, "\n".join(parts))


def build_federal():
    with open(DATA / "federal" / "divisions.json", encoding="utf-8") as f:
        entries = json.load(f)
    assert len(entries) == EXPECTED["canada"], \
        f"Federal: expected {EXPECTED['canada']} divisions, got {len(entries)}"
    out = ROOT / "ca"
    out.mkdir(exist_ok=True)
    sizes = []
    for i, e in enumerate(entries):
        blob = federal_page(i, e).encode("utf-8")
        write_blob(out / f"division-{i}.html", blob)
        sizes.append(len(blob))
